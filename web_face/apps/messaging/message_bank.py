def get_bank_file_path() -> Path:
    """Returns absolute path to data/whatsapp_message_bank.json."""
    data_dir = Path(settings.BASE_DIR) / "data"
    data_dir.mkdir(parents=True, exist_ok=True)
    return data_dir / "whatsapp_message_bank.json"


def seed_default_bank(force: bool = False) -> Dict[str, int]:
    """
    Seeds the SQLite database WhatsAppMessageBank and syncs with
    data/whatsapp_message_bank.json with all 250+ Egyptian Arabic variations.
    """
    from apps.messaging.models import WhatsAppMessageBank

    counts: Dict[str, int] = {}
    json_path = get_bank_file_path()

    for category, variations in MASTER_MESSAGE_BANK.items():
        bank_obj, created = WhatsAppMessageBank.objects.get_or_create(category=category)
        if created or force or len(bank_obj.variations) < 30:
            bank_obj.variations = variations
            bank_obj.save(update_fields=["variations", "updated_at"])
            counts[category] = len(variations)
        else:
            counts[category] = len(bank_obj.variations)

    # Save to JSON file as well
    try:
        current_data = {}
        for b in WhatsAppMessageBank.objects.all():
            current_data[b.category] = b.variations
        json_path.write_text(json.dumps(current_data, ensure_ascii=False, indent=2), encoding="utf-8")
        logger.info("Synced %d categories to %s", len(current_data), json_path)
    except Exception as exc:
        logger.warning("Could not sync message bank to JSON file: %s", exc)

    return counts


def get_variations_for_category(category: str) -> List[str]:
    """
    Retrieves variations for a category from DB if available, falling back to MASTER_MESSAGE_BANK.
    """
    from apps.messaging.models import WhatsAppMessageBank

    try:
        bank_obj = WhatsAppMessageBank.objects.filter(category=category).first()
        if bank_obj and bank_obj.variations and len(bank_obj.variations) > 0:
            return bank_obj.variations
    except Exception:
        pass

    return MASTER_MESSAGE_BANK.get(category, MASTER_MESSAGE_BANK.get("general", []))


def format_template_safely(template_str: str, context: dict) -> str:
    """
    Safely substitutes placeholders ({name}, {gym_name}, {end_date}, {date},
    {amount}, {currency}, {remaining}, {remaining_text}, {invoice_no}, {plan}, etc.)
    without raising KeyError on missing placeholders.
    """
    text = template_str

    # Process spin-syntax if present: {phrase 1|phrase 2|phrase 3}
    def _spin_replace(match):
        choices = match.group(1).split("|")
        return random.choice(choices).strip()

    # Avoid matching single-word placeholders like {name} by matching only those containing pipe '|'
    text = re.sub(r"\{([^{}]+?\|[^{}]+?)\}", _spin_replace, text)

    gym_name_val = context.get("gym_name")
    if not gym_name_val:
        try:
            from apps.core.models import GymProfile
            gym_name_val = GymProfile.get_solo().gym_name
        except Exception:
            gym_name_val = "سينا سبا | CINA SPA"

    replacements = {
        "{name}": str(context.get("name") or "كابتن"),
        "{gym_name}": str(gym_name_val or "سينا سبا | CINA SPA"),
        "{end_date}": str(context.get("end_date") or ""),
        "{date}": str(context.get("date") or context.get("today") or ""),
        "{today}": str(context.get("today") or context.get("date") or ""),
        "{amount}": str(context.get("amount") or context.get("amount_paid") or "0"),
        "{amount_paid}": str(context.get("amount_paid") or context.get("amount") or "0"),
        "{currency}": str(context.get("currency") or "جنيه"),
        "{remaining}": str(context.get("remaining") or context.get("remaining_amount") or "0"),
        "{remaining_amount}": str(context.get("remaining_amount") or context.get("remaining") or "0"),
        "{remaining_text}": str(context.get("remaining_text") or ""),
        "{invoice_no}": str(context.get("invoice_no") or ""),
        "{plan}": str(context.get("plan") or context.get("plan_name") or "الاشتراك"),
        "{plan_name}": str(context.get("plan_name") or context.get("plan") or "الاشتراك"),
        "{member_id}": str(context.get("member_id") or ""),
        "{days_left}": str(context.get("days_left") or "0"),
        "{phone}": str(context.get("phone") or ""),
    }

    for placeholder, val in replacements.items():
        text = text.replace(placeholder, val)

    return text.strip()


def get_random_message(category: str, context: Optional[dict] = None) -> str:
    """
    Selects a completely random template from the 50+ variations of `category`
    and returns the fully rendered message with all variables substituted.
    """
    if context is None:
        context = {}

    variations = get_variations_for_category(category)
    if not variations:
        variations = MASTER_MESSAGE_BANK.get(category, ["أهلاً يا كابتن {name} منورنا في {gym_name} 💪"])

    selected_template = random.choice(variations)
    return format_template_safely(selected_template, context)
